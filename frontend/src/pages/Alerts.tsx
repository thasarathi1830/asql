import React, { useState } from 'react';
import { demoAlerts } from '../lib/demoData';
import { Bell, ShieldAlert, CheckCircle2, ArrowRight, Filter } from 'lucide-react';
import { RiskBadge } from '../components/ui/RiskBadge';
import { Link } from 'react-router-dom';

export const Alerts: React.FC = () => {
  const [severityFilter, setSeverityFilter] = useState('ALL');
  const [sourceFilter, setSourceFilter] = useState('ALL');
  const [alertsList, setAlertsList] = useState(demoAlerts);

  const filtered = alertsList.filter((a) => {
    if (severityFilter !== 'ALL' && a.severity !== severityFilter) return false;
    return true;
  });

  const handleDismiss = (id: string) => {
    setAlertsList((prev) => prev.filter((a) => a.id !== id));
  };

  return (
    <div className="space-y-6 max-w-7xl mx-auto">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-phantom-border">
        <div>
          <div className="flex items-center gap-2">
            <Bell className="w-5 h-5 text-rose-400" />
            <h2 className="text-lg font-bold font-mono text-slate-100">Live Intelligence Alerts Queue</h2>
          </div>
          <p className="text-xs text-slate-400 mt-1">
            Real-time triggers generated by continuous graph monitoring, screening holds, and onboarding collisions
          </p>
        </div>

        <div className="flex items-center gap-2">
          {['ALL', 'CRITICAL', 'HIGH', 'MEDIUM'].map((lvl) => (
            <button
              key={lvl}
              onClick={() => setSeverityFilter(lvl)}
              className={`px-3 py-1 rounded text-xs font-mono transition-colors ${
                severityFilter === lvl
                  ? 'bg-rose-500 text-slate-950 font-bold'
                  : 'bg-slate-900 border border-slate-800 text-slate-400 hover:text-slate-200'
              }`}
            >
              {lvl}
            </button>
          ))}
        </div>
      </div>

      {/* Alerts List */}
      <div className="space-y-3">
        {filtered.map((al) => (
          <div
            key={al.id}
            className="p-5 rounded-xl bg-phantom-surface border border-phantom-border hover:border-slate-700 transition-colors flex flex-col md:flex-row md:items-center justify-between gap-4 shadow-lg"
          >
            <div className="space-y-1.5 flex-1">
              <div className="flex flex-wrap items-center gap-2">
                <RiskBadge level={al.severity} size="sm" />
                <span className="px-2 py-0.5 rounded bg-slate-900 text-[10px] font-mono text-slate-400 border border-slate-800">
                  {al.alert_type}
                </span>
                <span className="text-[10px] font-mono text-slate-500">
                  {new Date(al.created_at).toLocaleString()}
                </span>
              </div>
              <h3 className="text-sm font-bold text-slate-100">{al.title}</h3>
              <p className="text-xs text-slate-400 leading-relaxed max-w-3xl">{al.description}</p>
            </div>

            <div className="flex items-center gap-3">
              <button
                onClick={() => handleDismiss(al.id)}
                className="px-3 py-1.5 rounded bg-slate-900 hover:bg-slate-800 text-xs font-mono text-slate-400 border border-slate-800 transition-colors"
              >
                Dismiss
              </button>
              <Link
                to="/investigations/INV-2026-PHANTOM-001"
                className="flex items-center gap-1.5 px-4 py-1.5 rounded bg-rose-600 hover:bg-rose-500 text-slate-950 text-xs font-bold font-mono transition-colors shadow-lg shadow-rose-600/20"
              >
                Escalate Case <ArrowRight className="w-3.5 h-3.5" />
              </Link>
            </div>
          </div>
        ))}
      </div>
    </div>
  );
};

